-- 1. Tạo cơ sở dữ liệu
CREATE DATABASE IF NOT EXISTS QuanLyDonDatHang CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE QuanLyDonDatHang;

-- ====================================================
-- 2. TẠO CÁC BẢNG ĐỘC LẬP (BẢNG CHA - CHƯA CÓ KHÓA NGOẠI)
-- ====================================================

-- Bảng Đơn vị khách (đã gộp Đơn vị đặt và Đơn vị khách hàng)
CREATE TABLE DON_VI_KHACH (
    MaDV VARCHAR(20) PRIMARY KEY,
    TenDV VARCHAR(150) NOT NULL,
    DiaChi VARCHAR(255),
    DienThoai VARCHAR(20)
);

-- Bảng Hàng hóa
CREATE TABLE HANG (
    MaHang VARCHAR(20) PRIMARY KEY,
    TenHang VARCHAR(150) NOT NULL,
    DVTinh VARCHAR(50),
    MoTa TEXT
);

-- Bảng Nơi giao
CREATE TABLE NOI_GIAO (
    MaDDG VARCHAR(20) PRIMARY KEY,
    TenNoiGiao VARCHAR(255) NOT NULL
);

-- Bảng Người giao
CREATE TABLE NGUOI_GIAO (
    MaNG VARCHAR(20) PRIMARY KEY,
    HoTenNG VARCHAR(100) NOT NULL
);

-- ====================================================
-- 3. TẠO CÁC BẢNG PHỤ THUỘC (CÓ KHÓA NGOẠI THAM CHIẾU)
-- ====================================================

-- Bảng Người đặt (thuộc Đơn vị khách)
CREATE TABLE NGUOI_DAT (
    MaND VARCHAR(20) PRIMARY KEY,
    HoTenND VARCHAR(100) NOT NULL,
    MaDV VARCHAR(20) NOT NULL,
    FOREIGN KEY (MaDV) REFERENCES DON_VI_KHACH(MaDV) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Bảng Người nhận (thuộc Đơn vị khách)
CREATE TABLE NGUOI_NHAN (
    MaNN VARCHAR(20) PRIMARY KEY,
    HoTenNN VARCHAR(100) NOT NULL,
    MaDV VARCHAR(20) NOT NULL,
    FOREIGN KEY (MaDV) REFERENCES DON_VI_KHACH(MaDV) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Bảng Đơn đặt hàng
CREATE TABLE DON_DAT_HANG (
    SoDH VARCHAR(20) PRIMARY KEY,
    NgayDat DATE NOT NULL,
    MaND VARCHAR(20) NOT NULL,
    FOREIGN KEY (MaND) REFERENCES NGUOI_DAT(MaND) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Bảng Chi tiết đặt hàng (Khóa chính tổ hợp SoDH + MaHang)
CREATE TABLE CHI_TIET_DAT_HANG (
    SoDH VARCHAR(20) NOT NULL,
    MaHang VARCHAR(20) NOT NULL,
    SoLuongDat INT NOT NULL CHECK (SoLuongDat > 0),
    PRIMARY KEY (SoDH, MaHang),
    FOREIGN KEY (SoDH) REFERENCES DON_DAT_HANG(SoDH) ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (MaHang) REFERENCES HANG(MaHang) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Bảng Phiếu giao hàng
CREATE TABLE PHIEU_GIAO (
    SoPG VARCHAR(20) PRIMARY KEY,
    NgayGiao DATE NOT NULL,
    SoDH VARCHAR(20) NOT NULL,
    MaDDG VARCHAR(20) NOT NULL,
    MaNN VARCHAR(20) NOT NULL,
    MaNG VARCHAR(20) NOT NULL,
    FOREIGN KEY (SoDH) REFERENCES DON_DAT_HANG(SoDH) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (MaDDG) REFERENCES NOI_GIAO(MaDDG) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (MaNN) REFERENCES NGUOI_NHAN(MaNN) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (MaNG) REFERENCES NGUOI_GIAO(MaNG) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Bảng Chi tiết giao hàng (Khóa chính tổ hợp SoPG + MaHang)
CREATE TABLE CHI_TIET_GIAO_HANG (
    SoPG VARCHAR(20) NOT NULL,
    MaHang VARCHAR(20) NOT NULL,
    SoLuongGiao INT NOT NULL CHECK (SoLuongGiao > 0),
    DonGia DECIMAL(15, 2) NOT NULL CHECK (DonGia >= 0),
    ThanhTien DECIMAL(18, 2) GENERATED ALWAYS AS (SoLuongGiao * DonGia) STORED,
    PRIMARY KEY (SoPG, MaHang),
    FOREIGN KEY (SoPG) REFERENCES PHIEU_GIAO(SoPG) ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (MaHang) REFERENCES HANG(MaHang) ON UPDATE CASCADE ON DELETE RESTRICT
);
